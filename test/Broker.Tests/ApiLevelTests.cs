using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Astra.Credentials;
using Xunit;

namespace Broker.Tests;

public sealed class ApiLevelTests
{
  [Theory]
  [InlineData("2", "2")]
  [InlineData("2.0", "2")]
  [InlineData("2e0", "2")]
  [InlineData("2.50", "2.5")]
  [InlineData("9007199254740993", "9007199254740993")]
  [InlineData("2147483648", "2147483648")]
  [InlineData("2.0000000000000000000000000001", "2.0000000000000000000000000001")]
  [InlineData("79228162514264337593543950335", "79228162514264337593543950335")]
  [InlineData("1e-28", "0.0000000000000000000000000001")]
  [InlineData("250e-2", "2.5")]
  public void DecimalApiIsNormalizedExactlyWithoutDouble(string source, string expected)
  {
    var value = ApiLevel.Parse(source);
    Assert.Equal(expected, ApiLevel.Format(value));
    Assert.Equal(expected, Encoding.UTF8.GetString(Protocol.Encode(value)));
    Assert.Equal(value, Protocol.Decode<decimal>(Protocol.Parse(Encoding.UTF8.GetBytes(source))));
  }

  [Theory]
  [InlineData("-1")]
  [InlineData("\"2\"")]
  [InlineData("2.00000000000000000000000000001")]
  [InlineData("79228162514264337593543950336")]
  [InlineData("1e-29")]
  public void UnrepresentableApiIsRejectedRatherThanRounded(string source) =>
    Assert.ThrowsAny<Exception>(() => Protocol.Decode<decimal>(Protocol.Parse(Encoding.UTF8.GetBytes(source))));

  [Theory]
  [InlineData("0.0.1")]
  [InlineData("1.2.3-alpha.1+build.007")]
  [InlineData("99999999999999999999999999.2.3+meta")]
  public void SemVerIsIndependentFromApiCompatibility(string version)
  {
    ComponentContract.RequireSupported(version, 3.125m);
    Assert.Equal("api-incompatible", Assert.Throws<BrokerException>(() => ComponentContract.RequireSupported(version, 2.9999999999999999999999999999m)).Code);
  }

  [Theory]
  [InlineData("1.2")]
  [InlineData("01.2.3")]
  [InlineData("1.2.3-01")]
  [InlineData("1.2.3+")]
  public void SemVerSyntaxRemainsValidated(string version) => Assert.Throws<BrokerException>(() => ComponentContract.RequireSupported(version, 3m));

  [Fact]
  public void DecimalAuthUsesRawNumericTokensAndPreservesIntegerProofEncoding()
  {
    var greeting = new Greeting(1, 2.50m, "0.1.0-alpha+build", "vault", "generation", "nonce");
    var hello = new Hello(1, 2.125m, "client", "instance", "client-nonce", "", false);
    var expected = "[\"astra.pipe-auth.v1\",\"client\",1,2.5,\"0.1.0-alpha+build\",\"vault\",\"generation\",\"nonce\",2.125,\"client\",\"instance\",\"client-nonce\",false]";
    Assert.Equal(expected, Encoding.UTF8.GetString(PipeProtocol.AuthMessage(greeting, hello, "client")));
    Assert.Equal(CanonicalJson.Of(new object[] { "astra.pipe-auth.v1", "client", 1, 2, greeting.ComponentVersion,
      "vault", "generation", "nonce", 2, "client", "instance", "client-nonce", false }),
      PipeProtocol.AuthMessage(greeting with { ApiRevision = 2m }, hello with { ApiRevision = 2m }, "client"));
    // The general canonicalizer and existing migration format deliberately retain their integer-only numeric domain.
    Assert.Throws<BrokerException>(() => CanonicalJson.Of(new { value = 2.5m }));
    var vector = new
    {
      greeting,
      hello,
      verifier = Crypto.B64(SHA256.HashData(new byte[32])),
      authMessage = expected,
      proof = PipeProtocol.Proof(SHA256.HashData(new byte[32]), greeting, hello, "client")
    };
    File.WriteAllBytes(Path.Combine(AppContext.BaseDirectory, "interop-api-decimal.json"), Protocol.Encode(vector));
  }

  [Theory]
  [InlineData("2.125", "xftbVDZEKKp43LWPzBxRJeH65nXcJE_Eo2frO7m1BR0")]
  [InlineData("9007199254740993", "6wMD6lboJqd7LSxV1doABWMFQ_gCpryt49qP-kzt8a8")]
  [InlineData("2.0000000000000000000000000001", "AwmG1Ip8rZkToUvFBSXN58FBtW5qWbC1b19tj5aXE6Q")]
  public void FixedNodeCryptoGoldenVectorsMatchDotnetAuthBytesAndHmac(string level, string proof)
  {
    // Expected proofs are independently generated by Node crypto over literal canonical bytes,
    // and are also fixed assertions in the TypeScript SDK; never derive expectations from this encoder.
    var greeting = new Greeting(1, ApiLevel.Parse(level), "0.0.1-beta+build.7", "vault", "generation", "nonce");
    var hello = new Hello(1, ApiLevel.Parse(level), "client", "instance", "client-nonce", "", false);
    var expected = "[\"astra.pipe-auth.v1\",\"client\",1," + level + ",\"0.0.1-beta+build.7\",\"vault\",\"generation\",\"nonce\"," + level + ",\"client\",\"instance\",\"client-nonce\",false]";
    Assert.Equal(expected, Encoding.UTF8.GetString(PipeProtocol.AuthMessage(greeting, hello, "client")));
    Assert.Equal(proof, PipeProtocol.Proof(Crypto.Unb64("Zmh6rfhivXdsj8GLjp-OIAiXFIVu4jOzkCpZHQ1fKSU"), greeting, hello, "client"));
  }

  [Fact]
  public void ApiSchemaIsNumericRatherThanIntegerOrUnconstrainedConverter()
  {
    var schema = ProtocolSchema.Build();
    foreach (var type in new[] { "Greeting", "Hello", "ComponentManifest", "ComponentProbe" })
      Assert.Equal("number", schema["$defs"]![type]!["properties"]!["apiRevision"]!["type"]!.GetValue<string>());
  }
}
